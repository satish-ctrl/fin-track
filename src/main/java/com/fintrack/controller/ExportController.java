package com.fintrack.controller;

import com.fintrack.entity.User;
import com.fintrack.service.CurrentUserService;
import com.fintrack.service.EmailService;
import com.fintrack.service.ExportService;
import jakarta.validation.constraints.NotNull;
import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.ContentDisposition;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.Authentication;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.Locale;
import java.util.Map;

@RestController
@RequestMapping("/api/exports")
public class ExportController {

    private static final String PDF_TYPE = "application/pdf";
    private static final String EXCEL_TYPE =
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
    private static final long MAX_ATTACHMENT_SIZE = 10L * 1024L * 1024L;

    private final ExportService exportService;
    private final EmailService emailService;
    private final CurrentUserService currentUserService;

    public ExportController(
            ExportService exportService,
            EmailService emailService,
            CurrentUserService currentUserService) {
        this.exportService = exportService;
        this.emailService = emailService;
        this.currentUserService = currentUserService;
    }

    @GetMapping("/pdf")
    public ResponseEntity<byte[]> downloadPdf(
            Authentication authentication,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate fromDate,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate toDate) throws IOException {

        validateDates(fromDate, toDate);
        byte[] file = exportService.generatePdf(authentication.getName(), fromDate, toDate);
        return download(file, PDF_TYPE,
                "fintrack-report-" + fromDate + "-to-" + toDate + ".pdf");
    }

    @GetMapping("/excel")
    public ResponseEntity<byte[]> downloadExcel(
            Authentication authentication,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate fromDate,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate toDate) throws IOException {

        validateDates(fromDate, toDate);
        byte[] file = exportService.generateExcel(authentication.getName(), fromDate, toDate);
        return download(file, EXCEL_TYPE,
                "fintrack-report-" + fromDate + "-to-" + toDate + ".xlsx");
    }

    /**
     * Emails the exact statement attachment generated by the frontend download logic.
     * The recipient is resolved from the authenticated user's registered email.
     */
    @PostMapping(value = "/email", consumes = MediaType.MULTIPART_FORM_DATA_VALUE)
    public ResponseEntity<Map<String, String>> emailReport(
            Authentication authentication,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate fromDate,
            @RequestParam @NotNull
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE) LocalDate toDate,
            @RequestParam String format,
            @RequestPart("file") MultipartFile attachment) throws IOException {

        validateDates(fromDate, toDate);

        if (attachment == null || attachment.isEmpty()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "A report attachment is required.");
        }
        if (attachment.getSize() > MAX_ATTACHMENT_SIZE) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "The report attachment must not exceed 10 MB.");
        }

        User user = currentUserService.getCurrentActiveUser();
        if (user.getEmail() == null || user.getEmail().isBlank()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "The authenticated user has no registered email address.");
        }

        String normalizedFormat = format == null ? "" : format.trim().toLowerCase(Locale.ROOT);
        String expectedContentType;
        String expectedExtension;

        if ("pdf".equals(normalizedFormat)) {
            expectedContentType = PDF_TYPE;
            expectedExtension = ".pdf";
        } else if ("excel".equals(normalizedFormat) || "xlsx".equals(normalizedFormat)) {
            expectedContentType = EXCEL_TYPE;
            expectedExtension = ".xlsx";
        } else {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Unsupported format. Use pdf or excel.");
        }

        String originalFilename = attachment.getOriginalFilename();
        String filename = originalFilename == null || originalFilename.isBlank()
                ? "FinTrack-Statement-" + fromDate + "-to-" + toDate + expectedExtension
                : originalFilename.replaceAll("[\\r\\n\\\\/]", "_");

        if (!filename.toLowerCase(Locale.ROOT).endsWith(expectedExtension)) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "The attachment extension does not match the selected format.");
        }

        byte[] file = attachment.getBytes();
        if (file.length == 0) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "The report attachment is empty.");
        }

        emailService.sendEmailWithAttachment(
                user.getEmail(),
                "Your FinTrack Financial Report",
                "Your FinTrack financial statement for " + fromDate
                        + " to " + toDate + " is attached.",
                filename,
                expectedContentType,
                file
        );

        return ResponseEntity.ok(Map.of(
                "message", "Financial report emailed successfully.",
                "format", normalizedFormat
        ));
    }

    private void validateDates(LocalDate fromDate, LocalDate toDate) {
        if (fromDate == null || toDate == null) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Both fromDate and toDate are required.");
        }
        if (fromDate.isAfter(toDate)) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "fromDate cannot be after toDate.");
        }
    }

    private ResponseEntity<byte[]> download(byte[] file, String contentType, String filename) {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.parseMediaType(contentType));
        headers.setContentDisposition(
                ContentDisposition.attachment()
                        .filename(filename, StandardCharsets.UTF_8)
                        .build()
        );
        return ResponseEntity.ok().headers(headers).body(file);
    }
}
